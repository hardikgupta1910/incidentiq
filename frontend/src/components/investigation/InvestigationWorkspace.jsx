const PROVIDER_LABELS = {
  ollama: "Local Ollama",
  groq: "Groq",
  mistral: "Mistral",
};

function asArray(value) {
  return Array.isArray(value) ? value : [];
}

function getAnalysisSource(result) {
  return result?.analysisSource ?? result?.analysis_source;
}

function getAnalysisSourceLabel(result) {
  const source = getAnalysisSource(result);

  if (source === "local_ai") return "Local AI analysis";
  if (source === "groq") return "Groq cloud analysis";
  if (source === "mistral") return "Mistral cloud analysis";
  if (source === "rule_based_fallback") return "Rule-based fallback";

  return "Unknown / legacy result";
}

function getRequestedProviderLabel(result) {
  const provider =
    result?.requestedProvider ?? result?.requested_provider;

  return PROVIDER_LABELS[provider] || provider || "Not recorded";
}

function getConfidenceLabel(result) {
  const source = getAnalysisSource(result);

  if (["local_ai", "groq", "mistral"].includes(source)) {
    return "Model-reported confidence";
  }

  if (source === "rule_based_fallback") {
    return "Rule-based heuristic score";
  }

  return "Recorded heuristic score";
}

function getAnalysisNotice(result) {
  const source = getAnalysisSource(result);

  if (source === "rule_based_fallback") {
    return (
      "This result was generated by deterministic rules, not an AI model. " +
      "Its scores are rule-based heuristics, not measured probabilities. " +
      "Validate suggested checks before changing systems."
    );
  }

  if (["local_ai", "groq", "mistral"].includes(source)) {
    return (
      "AI-generated hypotheses are not verified findings. " +
      "Confidence is model-reported, not an independently calibrated probability. " +
      "Validate suggested checks before changing systems."
    );
  }

  return (
    "The analysis source was not recorded for this saved result. " +
    "Scores are not verified probabilities. Validate hypotheses and " +
    "suggested checks against the original evidence."
  );
}

function formatConfidence(value) {
  return typeof value === "number" && Number.isFinite(value)
    ? `${(value * 100).toFixed(0)}%`
    : "Not recorded";
}

function formatDateTime(value) {
  if (!value) return "Not available";

  const date = new Date(value);

  return Number.isNaN(date.getTime())
    ? "Not available"
    : date.toLocaleString();
}

function safeFileName(value) {
  return (
    String(value || "incident-report")
      .replace(/[^a-z0-9-_ ]/gi, "")
      .trim()
      .replace(/\s+/g, "-")
      .slice(0, 80) || "incident-report"
  );
}

function textBlock(value) {
  const text = String(value ?? "");
  const runs = text.match(/`+/g) || [];
  const fence = "`".repeat(
    Math.max(3, ...runs.map((run) => run.length + 1))
  );

  return `${fence}text\n${text}\n${fence}`;
}

function buildReportMarkdown(incident, result) {
  const events = asArray(incident.events);
  const hypotheses = [...asArray(result.hypotheses)].sort(
    (a, b) => a.rank - b.rank
  );
  const sources = asArray(result.retrievedSources);

  const lines = [
    "# Incident Investigation Report",
    "",
    "## Incident",
    "",
    textBlock(incident.title || "Untitled incident"),
    "",
    `- Incident ID: ${incident.id}`,
    `- Created: ${formatDateTime(incident.createdAt)}`,
    `- Source file: ${incident.sourceFilename || "Not available"}`,
    `- Investigation status: ${result.status || "Not available"}`,
    `- Requested provider: ${getRequestedProviderLabel(result)}`,
    `- Analysis source: ${getAnalysisSourceLabel(result)}`,
    `- Parsed log lines: ${incident.totalLogLines ?? events.length}`,
    `- Errors and critical events: ${incident.errorCount ?? "Not available"}`,
    `- Hypotheses: ${hypotheses.length}`,
    `- Retrieved knowledge passages: ${sources.length}`,
    "",
    "## Important limitations",
    "",
    getAnalysisNotice(result),
    "",
    "- Hypotheses are not independently verified findings.",
    "- Retrieved passages provide guidance; they do not prove an incident cause.",
    "- Retrieval scores are not confidence percentages.",
    "- Validate checks before executing commands or changing production systems.",
    "",
    "## Ranked hypotheses",
    "",
  ];

  if (!hypotheses.length) {
    lines.push("No hypotheses were returned.", "");
  }

  hypotheses.forEach((hypothesis, index) => {
    const evidence = asArray(hypothesis.evidence);
    const checks = asArray(hypothesis.suggestedChecks);

    lines.push(
      `### Hypothesis ${hypothesis.rank ?? index + 1}`,
      "",
      textBlock(hypothesis.summary || "No summary was returned."),
      "",
      `${getConfidenceLabel(result)}: ${formatConfidence(hypothesis.confidence)}`,
      "",
      "#### Supporting evidence",
      ""
    );

    if (!evidence.length) {
      lines.push("No supporting evidence was returned.", "");
    }

    evidence.forEach((item) => {
      const location = [
        item.sourceType || "Unknown source type",
        item.sourceFile,
        item.lineNumber != null ? `Line ${item.lineNumber}` : "",
        item.chunkIndex != null ? `Chunk ${item.chunkIndex}` : "",
      ]
        .filter(Boolean)
        .join(" | ");

      lines.push(location, "", textBlock(item.message), "");
    });

    lines.push("#### Suggested checks", "");

    if (!checks.length) {
      lines.push("No suggested checks were returned.", "");
    }

    checks.forEach((check, checkIndex) => {
      lines.push(
        `Check ${checkIndex + 1}`,
        "",
        textBlock(check),
        ""
      );
    });
  });

  lines.push("## Retrieved knowledge", "");

  if (!sources.length) {
    lines.push("No retrieved knowledge passages were returned.", "");
  }

  sources.forEach((source, index) => {
    lines.push(
      `### Passage ${index + 1}`,
      "",
      textBlock(source.sourceFile || "Unknown source"),
      "",
      `Chunk: ${source.chunkIndex ?? "Not available"}`,
      `Retrieval score: ${
        typeof source.score === "number"
          ? source.score.toFixed(4)
          : "Not available"
      }`,
      "",
      textBlock(source.text || "No passage text was returned."),
      ""
    );
  });

  lines.push(
    "## Export",
    "",
    `Report generated: ${new Date().toISOString()}`,
    "",
    "This export contains the investigation result displayed at export time.",
    ""
  );

  return lines.join("\n");
}

function CopyButton({ text, label }) {
  const [copied, setCopied] = useState(false);
  const [failed, setFailed] = useState(false);

  async function handleCopy() {
    try {
      await navigator.clipboard.writeText(String(text ?? ""));
      setCopied(true);
      setFailed(false);
    } catch {
      setCopied(false);
      setFailed(true);
    }
  }

  return (
    <div className="flex shrink-0 items-center gap-2">
      <button
        type="button"
        onClick={handleCopy}
        onBlur={() => setCopied(false)}
        aria-label={copied ? `Copied ${label}` : `Copy ${label}`}
        title={copied ? "Copied" : `Copy ${label}`}
        className="flex h-8 items-center gap-2 rounded-md border border-line px-2 text-xs text-text-secondary hover:bg-elevated"
      >
        {copied ? (
          <Check size={14} aria-hidden="true" />
        ) : (
          <Copy size={14} aria-hidden="true" />
        )}
        {copied ? "Copied" : "Copy"}
      </button>

      {failed && (
        <span role="status" className="text-xs text-red-300">
          Copy unavailable
        </span>
      )}
    </div>
  );
}

function EvidenceItem({ evidence, events }) {
  const relatedLog =
    evidence.lineNumber != null
      ? events.find(
          (event) => event.lineNumber === evidence.lineNumber
        )
      : null;

  return (
    <li className="border-l-2 border-line pl-4">
      <div className="flex flex-wrap gap-x-3 gap-y-1 text-xs text-text-muted">
        <span>{evidence.sourceType}</span>

        {evidence.sourceFile && (
          <span className="break-all font-mono">
            {evidence.sourceFile}
          </span>
        )}

        {evidence.lineNumber != null && (
          <span>Line {evidence.lineNumber}</span>
        )}

        {evidence.chunkIndex != null && (
          <span>Chunk {evidence.chunkIndex}</span>
        )}
      </div>

      <p className="mt-2 whitespace-pre-wrap break-words text-sm leading-6 text-text-secondary">
        {evidence.message}
      </p>

      {relatedLog && (
        <details className="mt-2">
          <summary className="cursor-pointer text-xs text-accent">
            View referenced log event
          </summary>
          <pre className="mt-2 whitespace-pre-wrap break-words rounded-md border border-line bg-canvas p-3 text-xs leading-6 text-text-secondary">
            {relatedLog.message}
          </pre>
        </details>
      )}
    </li>
  );
}

function HypothesisPanel({ hypothesis, events, result }) {
  const evidence = asArray(hypothesis.evidence);
  const checks = asArray(hypothesis.suggestedChecks);

  return (
    <article className="rounded-lg border border-line bg-surface p-5 sm:p-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <span className="text-xs font-medium uppercase tracking-wider text-accent">
          Hypothesis {hypothesis.rank}
        </span>

        {typeof hypothesis.confidence === "number" &&
          Number.isFinite(hypothesis.confidence) && (
            <span
              title="Heuristic assessment, not an independently verified probability."
              className="rounded-md border border-line px-2 py-1 text-xs text-text-secondary"
            >
              {getConfidenceLabel(result)}
              {": "}
              {formatConfidence(hypothesis.confidence)}
            </span>
          )}
      </div>

      <h3 className="mt-4 whitespace-pre-wrap break-words text-base font-medium leading-7">
        {hypothesis.summary}
      </h3>

      <section className="mt-6">
        <h4 className="text-xs font-semibold uppercase tracking-wider text-text-muted">
          Supporting evidence
        </h4>

        {evidence.length ? (
          <ul className="mt-4 space-y-5">
            {evidence.map((item, index) => (
              <EvidenceItem
                key={index}
                evidence={item}
                events={events}
              />
            ))}
          </ul>
        ) : (
          <p className="mt-3 text-sm text-text-secondary">
            No supporting evidence was returned for this hypothesis.
          </p>
        )}
      </section>

      <section className="mt-6 border-t border-line pt-5">
        <h4 className="text-xs font-semibold uppercase tracking-wider text-text-muted">
          Suggested checks
        </h4>

        {checks.length ? (
          <ol className="mt-4 space-y-4">
            {checks.map((check, index) => (
              <li
                key={index}
                className="flex flex-wrap items-start gap-3"
              >
                <span className="flex h-6 w-6 shrink-0 items-center justify-center rounded border border-line font-mono text-xs text-text-muted">
                  {index + 1}
                </span>

                <p className="min-w-0 flex-1 whitespace-pre-wrap break-words text-sm leading-6 text-text-secondary">
                  {check}
                </p>

                <CopyButton
                  text={check}
                  label={`suggested check ${index + 1}`}
                />
              </li>
            ))}
          </ol>
        ) : (
          <p className="mt-3 text-sm text-text-secondary">
            No suggested checks were returned.
          </p>
        )}
      </section>
    </article>
  );
}

export default function InvestigationWorkspace({
  incident: rawIncident,
}) {
  const incident = useMemo(
    () => normalizeApiData(rawIncident),
    [rawIncident]
  );

  const [result, setResult] = useState(
    () => incident.investigation || null
  );
  const [running, setRunning] = useState(false);
  const [error, setError] = useState("");
  const [exportError, setExportError] = useState("");

  const [privacyPolicy, setPrivacyPolicy] = useState(null);
  const [selectedProvider, setSelectedProvider] = useState("ollama");
  const [activeProvider, setActiveProvider] = useState(null);

  const investigationLock = useRef(false);

  const policyEnabled =
    privacyPolicy?.enabled === true ||
    privacyPolicy?.locked === true;

  const policyLoaded =
    typeof privacyPolicy?.enabled === "boolean";

  const policyProviderList =
    privacyPolicy?.allowed_providers ??
    privacyPolicy?.allowedProviders;

  const allowedProviders = !policyLoaded
    ? []
    : policyEnabled
      ? ["ollama"]
      : asArray(policyProviderList).filter((provider) =>
          Object.prototype.hasOwnProperty.call(
            PROVIDER_LABELS,
            provider
          )
        );

  const effectiveProvider = allowedProviders.includes(selectedProvider)
    ? selectedProvider
    : allowedProviders[0] || "";

  const cloudSelected =
    effectiveProvider === "groq" ||
    effectiveProvider === "mistral";

  const hypotheses = useMemo(
    () =>
      [...asArray(result?.hypotheses)].sort(
        (a, b) => a.rank - b.rank
      ),
    [result]
  );

  const sources = asArray(result?.retrievedSources);
  const events = asArray(incident.events);

  async function runInvestigation() {
    if (investigationLock.current) return;

    if (
      !policyLoaded ||
      !allowedProviders.includes(effectiveProvider)
    ) {
      setError(
        "Load the workspace privacy policy and select an allowed provider."
      );
      return;
    }

    const provider = effectiveProvider;
    const isCloud = provider !== "ollama";

    if (
      isCloud &&
      !window.confirm(
        `Run this investigation using ${PROVIDER_LABELS[provider]}?\n\n` +
          "Incident logs and retrieved operational documentation will " +
          "be sent to this external provider.\n\n" +
          "Only the selected analysis provider will be used. " +
          "Continue only if this data is approved for external processing."
      )
    ) {
      return;
    }

    investigationLock.current = true;
    setActiveProvider(provider);
    setRunning(true);
    setError("");

    try {
      const response = normalizeApiData(
        await investigationService.investigate(incident.id, {
          provider,
          confirmExternalProcessing: isCloud,
        })
      );

      if (
        String(response?.incidentId) !== String(incident.id) ||
        !Array.isArray(response?.hypotheses)
      ) {
        setError(
          "The API returned an unexpected investigation response. " +
            "Reopen the incident to check its saved result."
        );
        return;
      }

      setResult(response);
    } catch (requestError) {
      setError(getApiErrorMessage(requestError));
    } finally {
      investigationLock.current = false;
      setRunning(false);
      setActiveProvider(null);
    }
  }

  function exportReport() {
    setExportError("");

    if (!result) {
      setExportError(
        "Run or open an investigation before exporting a report."
      );
      return;
    }

    let url = null;
    let link = null;

    try {
      const markdown = buildReportMarkdown(incident, result);
      const blob = new Blob([markdown], {
        type: "text/markdown;charset=utf-8",
      });

      url = URL.createObjectURL(blob);
      link = document.createElement("a");
      link.href = url;
      link.download =
        `${safeFileName(incident.title)}-report.md`;

      document.body.appendChild(link);
      link.click();
    } catch {
      setExportError(
        "The report could not be exported. Try again."
      );
    } finally {
      link?.remove();

      if (url) {
        const downloadUrl = url;
        setTimeout(
          () => URL.revokeObjectURL(downloadUrl),
          1000
        );
      }
    }
  }

  return (
    <section
      aria-labelledby="investigation-heading"
      aria-busy={running}
      className="mt-9 border-t border-line pt-8"
    >
      <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <div className="flex items-center gap-2">
            <FlaskConical
              size={20}
              className="text-accent"
              aria-hidden="true"
            />
            <h2
              id="investigation-heading"
              className="text-xl font-semibold tracking-tight"
            >
              Incident investigation
            </h2>
          </div>

          <p className="mt-2 max-w-2xl text-sm leading-6 text-text-secondary">
            Review possible causes against log evidence and
            retrieved operational knowledge.
          </p>
        </div>

        <button
          type="button"
          onClick={exportReport}
          disabled={!result}
          className="flex h-10 shrink-0 items-center justify-center gap-2 rounded-md border border-line px-4 text-sm font-medium text-text-primary hover:bg-elevated disabled:cursor-not-allowed disabled:opacity-50"
        >
          <Download size={16} aria-hidden="true" />
          Export report
        </button>
      </div>

      <PrivacyControl
        onPolicyChange={setPrivacyPolicy}
        disabled={running}
      />

      <div className="mt-5 rounded-lg border border-line bg-surface p-5">
        <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
          <div className="min-w-0">
            <label
              htmlFor="investigation-provider"
              className="block text-sm font-medium"
            >
              Investigation provider
            </label>

            <select
              id="investigation-provider"
              value={effectiveProvider}
              disabled={running || !allowedProviders.length}
              onChange={(event) =>
                setSelectedProvider(event.target.value)
              }
              aria-describedby="investigation-provider-help"
              className="mt-2 h-10 w-full rounded-md border border-line bg-canvas px-3 text-sm outline-none focus:border-accent disabled:opacity-50 sm:min-w-[220px]"
            >
              {!allowedProviders.length && (
                <option value="">
                  {policyLoaded
                    ? "No allowed providers"
                    : "Load privacy policy first"}
                </option>
              )}

              {allowedProviders.map((provider) => (
                <option key={provider} value={provider}>
                  {PROVIDER_LABELS[provider]}
                </option>
              ))}
            </select>
          </div>

          <button
            type="button"
            onClick={runInvestigation}
            disabled={running || !allowedProviders.length}
            className="flex h-10 shrink-0 items-center justify-center gap-2 rounded-md bg-accent px-4 text-sm font-medium text-white hover:bg-accent-hover disabled:cursor-not-allowed disabled:opacity-60"
          >
            {running ? (
              <LoaderCircle
                size={17}
                className="animate-spin"
                aria-hidden="true"
              />
            ) : (
              <Play size={16} aria-hidden="true" />
            )}
            {running
              ? "Investigating..."
              : result
                ? "Run again"
                : "Run investigation"}
          </button>
        </div>

        <p
          id="investigation-provider-help"
          className="mt-3 text-xs leading-6 text-text-muted"
        >
          Embeddings always use Ollama. Exactly one selected
          provider performs analysis. Ollama must remain available
          for embedding-based retrieval, including cloud runs.
        </p>

        {policyLoaded && policyEnabled && (
          <p className="mt-2 text-xs leading-6 text-text-secondary">
            Privacy mode permits local Ollama analysis only.
            An administrator must explicitly permit cloud processing
            before Groq or Mistral can be selected.
          </p>
        )}

        {cloudSelected && (
          <p className="mt-2 text-xs leading-6 text-warning">
            {PROVIDER_LABELS[effectiveProvider]} is external.
            Logs and retrieved guidance will leave the local
            environment after you confirm. Cloud failures do not
            automatically switch analysis providers.
          </p>
        )}
      </div>

      {running && (
        <div
          role="status"
          className="mt-5 rounded-md border border-accent/30 bg-accent/5 px-4 py-3 text-sm leading-6 text-text-secondary"
        >
          Investigation requested using{" "}
          {PROVIDER_LABELS[activeProvider] || "the selected provider"}.
          Waiting for retrieval, analysis, and validation.
          {result &&
            " The previous result remains visible and exportable below."}
        </div>
      )}

      {error && (
        <div
          role="alert"
          className="mt-5 rounded-md border border-critical/30 bg-critical/5 px-4 py-3 text-sm leading-6 text-red-300"
        >
          {error}
        </div>
      )}

      {exportError && (
        <div
          role="alert"
          className="mt-5 rounded-md border border-critical/30 bg-critical/5 px-4 py-3 text-sm leading-6 text-red-300"
        >
          {exportError}
        </div>
      )}

      {!result && !running && (
        <div className="mt-6 rounded-lg border border-dashed border-line p-6">
          <h3 className="text-sm font-medium">
            No saved investigation
          </h3>
          <p className="mt-2 max-w-xl text-sm leading-6 text-text-secondary">
            Choose an allowed provider and run an investigation
            to generate ranked hypotheses, evidence references,
            and suggested diagnostic checks.
          </p>
        </div>
      )}

      {result && (
        <>
          <div className="mt-6 flex flex-wrap items-center gap-x-5 gap-y-2 border-y border-line py-3 text-xs text-text-secondary">
            <span>
              Status:{" "}
              <span className="text-text-primary">
                {result.status || "Not recorded"}
              </span>
            </span>

            <span>
              Requested provider:{" "}
              <span className="text-text-primary">
                {getRequestedProviderLabel(result)}
              </span>
            </span>

            <span>
              Analysis source:{" "}
              <span className="text-text-primary">
                {getAnalysisSourceLabel(result)}
              </span>
            </span>

            <span>{hypotheses.length} hypotheses</span>
            <span>{sources.length} retrieved sources</span>
          </div>

          <p className="mt-4 text-xs leading-6 text-text-muted">
            {getAnalysisNotice(result)}
          </p>

          <div className="mt-6 grid min-w-0 items-start gap-6 xl:grid-cols-[minmax(0,1fr)_340px]">
            <div className="min-w-0 space-y-5">
              {hypotheses.length ? (
                hypotheses.map((hypothesis, index) => (
                  <HypothesisPanel
                    key={`${hypothesis.rank}-${index}`}
                    hypothesis={hypothesis}
                    events={events}
                    result={result}
                  />
                ))
              ) : (
                <div className="rounded-lg border border-line bg-surface p-6 text-sm text-text-secondary">
                  The backend returned no hypotheses.
                </div>
              )}
            </div>

            <aside
              aria-label="Retrieved knowledge"
              className="min-w-0 rounded-lg border border-line bg-surface p-5"
            >
              <div className="flex items-center gap-2">
                <BookOpen
                  size={17}
                  className="text-accent"
                  aria-hidden="true"
                />
                <h3 className="text-sm font-semibold">
                  Retrieved knowledge
                </h3>
              </div>

              <p className="mt-3 text-xs leading-6 text-text-muted">
                Retrieval scores are shown as returned by the
                backend. They are not confidence percentages.
              </p>

              {sources.length ? (
                <div className="mt-5 divide-y divide-line">
                  {sources.map((source, index) => (
                    <details
                      key={`${source.sourceFile}-${source.chunkIndex}-${index}`}
                      className="py-4 first:pt-0"
                    >
                      <summary className="cursor-pointer break-words text-sm font-medium text-text-primary">
                        {source.sourceFile || "Unknown source"}
                      </summary>

                      <div className="mt-3 flex flex-wrap gap-3 text-xs text-text-muted">
                        <span>
                          Chunk {source.chunkIndex ?? "Not recorded"}
                        </span>
                        <span>
                          Score{" "}
                          {typeof source.score === "number"
                            ? source.score.toFixed(4)
                            : "Not available"}
                        </span>
                      </div>

                      <p className="mt-3 whitespace-pre-wrap break-words text-xs leading-6 text-text-secondary">
                        {source.text}
                      </p>

                      <div className="mt-3">
                        <CopyButton
                          text={source.text}
                          label="retrieved passage"
                        />
                      </div>
                    </details>
                  ))}
                </div>
              ) : (
                <p className="mt-5 text-sm leading-6 text-text-secondary">
                  No retrieved sources were returned for this
                  investigation.
                </p>
              )}
            </aside>
          </div>
        </>
      )}
    </section>
  );
}