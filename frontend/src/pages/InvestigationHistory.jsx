import { useEffect, useState } from "react";
import { Link, useSearchParams } from "react-router-dom";
import { Download, LoaderCircle } from "lucide-react";
import historyService from "../services/historyService";
import { getApiErrorMessage } from "../services/api";

const buttonClass =
  "inline-flex items-center gap-2 rounded-md border border-line px-3 py-2 text-sm hover:bg-elevated";

function array(value) {
  return Array.isArray(value) ? value : [];
}

function formatDate(value) {
  if (!value) return "Not recorded";
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? "Not recorded"
    : date.toLocaleString();
}

function sourceLabel(result) {
  if (result?.analysis_source === "local_ai") return "Local AI analysis";
  if (result?.analysis_source === "rule_based_fallback") {
    return "Rule-based fallback";
  }
  return "Unknown / legacy result";
}

function confidenceLabel(result) {
  if (result?.analysis_source === "local_ai") {
    return "Model-reported confidence";
  }
  if (result?.analysis_source === "rule_based_fallback") {
    return "Rule-based heuristic score";
  }
  return "Recorded heuristic score";
}

function confidenceValue(value) {
  return typeof value === "number" && Number.isFinite(value)
    ? `${(value * 100).toFixed(0)}%`
    : "Not recorded";
}

function analysisNotice(result) {
  if (result?.analysis_source === "rule_based_fallback") {
    return "Generated by deterministic rules, not an AI model. " +
      "Scores are rule-based heuristics, not measured probabilities.";
  }
  if (result?.analysis_source === "local_ai") {
    return "AI-generated hypotheses are not verified findings. " +
      "Confidence is model-reported, not a measured probability.";
  }
  return "The analysis source was not recorded. " +
    "Do not infer whether this saved result came from AI or rules.";
}

function safeFilename(value) {
  return String(value || "saved-investigation")
    .replace(/[^a-z0-9-_ ]/gi, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 80) || "saved-investigation";
}

function textBlock(value) {
  const text = String(value ?? "");
  const runs = text.match(/`+/g) || [];
  const fence = "`".repeat(
    Math.max(3, ...runs.map((run) => run.length + 1))
  );
  return `${fence}text\n${text}\n${fence}`;
}

function buildHistoryMarkdown(record) {
  const result = record.result || {};
  const hypotheses = [...array(result.hypotheses)]
    .sort((a, b) => a.rank - b.rank);
  const sources = array(result.retrieved_sources);

  const lines = [
    "# Saved Investigation Report",
    "",
    `- Snapshot ID: ${record.id}`,
    `- Incident ID: ${record.incident_id}`,
    `- Recorded at: ${record.recorded_at || "Not recorded"}`,
    `- Snapshot status: ${record.status || "Not recorded"}`,
    `- Investigation status: ${result.status || "Not recorded"}`,
    `- Analysis source: ${sourceLabel(result)}`,
    `- Hypotheses: ${hypotheses.length}`,
    `- Retrieved knowledge passages: ${sources.length}`,
    "",
    "## Incident title",
    "",
    textBlock(record.incident_title || "Not recorded"),
    "",
    "## Snapshot scope and limitations",
    "",
    "This report exports the selected saved investigation snapshot.",
    "It does not rerun analysis or substitute the incident's latest result.",
    "",
    analysisNotice(result),
    "",
    "Hypotheses are not verified root causes. Retrieved knowledge provides",
    "guidance, not proof. Review all checks before changing systems.",
    "",
    "Exact model identity, execution timing, original incident creation time,",
    "and log counts are not supplied by this history record.",
    "",
    "## Ranked hypotheses",
    "",
  ];

  if (!hypotheses.length) {
    lines.push("No hypotheses were saved.", "");
  }

  hypotheses.forEach((hypothesis, index) => {
    lines.push(
      `### Hypothesis ${hypothesis.rank ?? index + 1}`,
      "",
      textBlock(hypothesis.summary || "No summary was saved."),
      "",
      `${confidenceLabel(result)}: ${confidenceValue(hypothesis.confidence)}`,
      "",
      "#### Evidence",
      ""
    );

    const evidence = array(hypothesis.evidence);

    if (!evidence.length) {
      lines.push("No evidence references were saved.", "");
    }

    evidence.forEach((item) => {
      const location = [
        item.source_type || "Unknown source type",
        item.source_file,
        item.line_number != null ? `Line ${item.line_number}` : "",
        item.chunk_index != null ? `Chunk ${item.chunk_index}` : "",
      ].filter(Boolean).join(" | ");

      lines.push(location, "", textBlock(item.message), "");
    });

    lines.push("#### Suggested checks", "");

    const checks = array(hypothesis.suggested_checks);

    if (!checks.length) {
      lines.push("No suggested checks were saved.", "");
    }

    checks.forEach((check, checkIndex) => {
      lines.push(
        `Check ${checkIndex + 1}`,
        "",
        textBlock(check),
        ""
      );
    });
  });

  lines.push("## Retrieved knowledge", "");

  if (!sources.length) {
    lines.push("No retrieved sources were saved.", "");
  }

  sources.forEach((source, index) => {
    lines.push(
      `### Passage ${index + 1}`,
      "",
      textBlock(source.source_file || "Unknown file"),
      "",
      `Chunk: ${source.chunk_index ?? "Not recorded"}`,
      `Retrieval score: ${source.score ?? "Not recorded"}`,
      "Retrieval scores are not confidence percentages.",
      "",
      textBlock(source.text),
      ""
    );
  });

  lines.push(
    "## Export",
    "",
    `Exported at: ${new Date().toISOString()}`,
    "Generated locally in the browser from the selected saved record.",
    ""
  );

  return lines.join("\n");
}

function download(content, filename, type) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");

  try {
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
  } finally {
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }
}

function SavedResult({ id }) {
  const [record, setRecord] = useState(null);
  const [error, setError] = useState("");
  const [exportError, setExportError] = useState("");
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    const controller = new AbortController();
    setRecord(null);
    setError("");
    setExportError("");

    historyService.get(id, { signal: controller.signal })
      .then((data) => {
        if (!controller.signal.aborted) setRecord(data);
      })
      .catch((err) => {
        if (!controller.signal.aborted) {
          setError(getApiErrorMessage(err));
        }
      });

    return () => controller.abort();
  }, [id, attempt]);

  function exportRecord(format) {
    setExportError("");

    try {
      if (format === "json") {
        download(
          JSON.stringify(record, null, 2),
          `incidentiq-investigation-${safeFilename(record.id)}.json`,
          "application/json;charset=utf-8"
        );
      } else {
        download(
          buildHistoryMarkdown(record),
          `${safeFilename(record.incident_title)}-${safeFilename(record.id)}-history-report.md`,
          "text/markdown;charset=utf-8"
        );
      }
    } catch {
      setExportError("Export failed. Please try again.");
    }
  }

  if (error) {
    return (
      <div className="mt-6">
        <p role="alert" className="text-sm text-red-300">{error}</p>
        <button
          type="button"
          onClick={() => setAttempt((value) => value + 1)}
          className="mt-3 text-sm text-accent"
        >
          Retry
        </button>
      </div>
    );
  }

  if (!record) {
    return (
      <p role="status" className="mt-6 text-sm text-text-secondary">
        Loading saved investigation...
      </p>
    );
  }

  const result = record.result || {};
  const hypotheses = [...array(result.hypotheses)]
    .sort((a, b) => a.rank - b.rank);
  const sources = array(result.retrieved_sources);

  return (
    <section className="mt-8 border-t border-line pt-6">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div className="min-w-0">
          <h2 className="text-lg font-semibold">Saved investigation</h2>
          <Link
            to={`/incidents/${encodeURIComponent(record.incident_id)}`}
            className="mt-2 inline-block break-words text-sm text-accent hover:underline"
          >
            {record.incident_title}
          </Link>
          <p className="mt-2 break-all font-mono text-xs text-text-muted">
            {record.id}
          </p>
        </div>

        <div className="flex flex-wrap gap-2">
          <button
            type="button"
            onClick={() => exportRecord("markdown")}
            className={buttonClass}
          >
            <Download size={16} aria-hidden="true" />
            Export Markdown
          </button>
          <button
            type="button"
            onClick={() => exportRecord("json")}
            className={buttonClass}
          >
            <Download size={16} aria-hidden="true" />
            Export JSON
          </button>
        </div>
      </div>

      {exportError && (
        <p role="alert" className="mt-4 text-sm text-red-300">
          {exportError}
        </p>
      )}

      <p className="mt-4 text-xs leading-6 text-text-muted">
        Recorded {formatDate(record.recorded_at)} | {record.status}
        {" | "}Analysis source: {sourceLabel(result)}
      </p>
      <p className="mt-2 text-xs leading-6 text-text-muted">
        {analysisNotice(result)} Validate all suggested checks.
        Exact model identity and execution timing were not recorded.
        This view shows the saved snapshot, not the latest incident result.
      </p>

      <div className="mt-5 space-y-5">
        {hypotheses.map((hypothesis, index) => {
          const evidence = array(hypothesis.evidence);
          const checks = array(hypothesis.suggested_checks);

          return (
            <article
              key={`${hypothesis.rank}-${index}`}
              className="rounded-lg border border-line bg-surface p-5"
            >
              <p className="text-xs text-accent">
                Hypothesis {hypothesis.rank} | {confidenceLabel(result)}
                {": "}{confidenceValue(hypothesis.confidence)}
              </p>
              <h3 className="mt-3 whitespace-pre-wrap break-words text-base leading-7">
                {hypothesis.summary}
              </h3>

              <h4 className="mt-5 text-xs font-semibold uppercase tracking-wider text-text-muted">
                Evidence
              </h4>
              <ul className="mt-3 space-y-3">
                {evidence.map((item, evidenceIndex) => (
                  <li
                    key={evidenceIndex}
                    className="border-l-2 border-line pl-3 text-sm leading-6 text-text-secondary"
                  >
                    <span className="break-words text-xs text-text-muted">
                      {item.source_type}
                      {item.source_file ? ` | ${item.source_file}` : ""}
                      {item.line_number != null ? ` | Line ${item.line_number}` : ""}
                      {item.chunk_index != null ? ` | Chunk ${item.chunk_index}` : ""}
                    </span>
                    <p className="whitespace-pre-wrap break-words">
                      {item.message}
                    </p>
                  </li>
                ))}
              </ul>
              {!evidence.length && (
                <p className="mt-2 text-sm text-text-secondary">
                  No evidence references were saved.
                </p>
              )}

              <h4 className="mt-5 text-xs font-semibold uppercase tracking-wider text-text-muted">
                Suggested checks
              </h4>
              <ol className="mt-3 list-decimal space-y-2 pl-5 text-sm leading-6 text-text-secondary">
                {checks.map((check, checkIndex) => (
                  <li key={checkIndex} className="whitespace-pre-wrap break-words">
                    {check}
                  </li>
                ))}
              </ol>
              {!checks.length && (
                <p className="mt-2 text-sm text-text-secondary">
                  No suggested checks were saved.
                </p>
              )}
            </article>
          );
        })}
        {!hypotheses.length && (
          <p className="text-sm text-text-secondary">
            No hypotheses were saved.
          </p>
        )}
      </div>

      <h3 className="mt-7 text-sm font-semibold">Retrieved knowledge</h3>
      {sources.map((source, index) => (
        <details
          key={index}
          className="mt-3 rounded-md border border-line bg-surface p-4"
        >
          <summary className="cursor-pointer break-words text-sm">
            {source.source_file} | Chunk {source.chunk_index}
          </summary>
          <p className="mt-2 text-xs text-text-muted">
            Retrieval score: {source.score} - not a confidence percentage
          </p>
          <p className="mt-3 whitespace-pre-wrap break-words text-sm leading-6 text-text-secondary">
            {source.text}
          </p>
        </details>
      ))}
      {!sources.length && (
        <p className="mt-3 text-sm text-text-secondary">
          No retrieved sources were saved.
        </p>
      )}
    </section>
  );
}

export default function InvestigationHistory() {
  const [params, setParams] = useSearchParams();
  const selectedId = params.get("id");
  const [input, setInput] = useState("");
  const [query, setQuery] = useState("");
  const [page, setPage] = useState(0);
  const [attempt, setAttempt] = useState(0);
  const [data, setData] = useState({ items: [], total: 0 });
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    const controller = new AbortController();
    setLoading(true);
    setError("");

    historyService.list({
      search: query,
      offset: page * 10,
      signal: controller.signal,
    })
      .then((response) => {
        if (controller.signal.aborted) return;

        setData(response);
        const lastPage = Math.max(
          0,
          Math.ceil(response.total / 10) - 1
        );
        if (page > lastPage) setPage(lastPage);
      })
      .catch((err) => {
        if (!controller.signal.aborted) {
          setError(getApiErrorMessage(err));
        }
      })
      .finally(() => {
        if (!controller.signal.aborted) setLoading(false);
      });

    return () => controller.abort();
  }, [query, page, attempt]);

  return (
    <div className="min-w-0">
      <h1 className="text-2xl font-semibold tracking-tight">
        Investigation History
      </h1>
      <p className="mt-2 text-sm leading-6 text-text-secondary">
        Review and export snapshots from previous investigation runs.
      </p>

      <form
        onSubmit={(event) => {
          event.preventDefault();
          setQuery(input.trim());
          setPage(0);
          setAttempt((value) => value + 1);
        }}
        className="mt-6 flex flex-wrap gap-2"
      >
        <input
          type="search"
          aria-label="Search investigation history"
          placeholder="Search incident title or ID"
          value={input}
          onChange={(event) => setInput(event.target.value)}
          className="h-10 w-full max-w-md rounded-md border border-line bg-surface px-3 text-sm outline-none focus:border-accent"
        />
        <button type="submit" className={buttonClass}>Search</button>
        <button
          type="button"
          disabled={loading}
          onClick={() => setAttempt((value) => value + 1)}
          className={`${buttonClass} disabled:opacity-40`}
        >
          Refresh
        </button>
      </form>

      {loading ? (
        <p role="status" className="mt-6 flex items-center gap-2 text-sm text-text-secondary">
          <LoaderCircle size={17} className="animate-spin" aria-hidden="true" />
          Loading history...
        </p>
      ) : error ? (
        <div className="mt-6">
          <p role="alert" className="text-sm text-red-300">{error}</p>
          <button
            type="button"
            onClick={() => setAttempt((value) => value + 1)}
            className="mt-3 text-sm text-accent"
          >
            Retry
          </button>
        </div>
      ) : (
        <>
          <div className="technical-scroll mt-5 overflow-x-auto rounded-lg border border-line bg-surface">
            <table className="w-full text-left text-sm">
              <caption className="sr-only">
                Saved investigation runs, newest first
              </caption>
              <thead className="border-b border-line bg-sidebar text-xs text-text-muted">
                <tr>
                  {["Incident", "Investigation", "Status", "Recorded", "Action"].map((heading) => (
                    <th scope="col" key={heading} className="px-4 py-3 font-medium">
                      {heading}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-line">
                {array(data.items).map((item) => (
                  <tr key={item.id}>
                    <td className="min-w-[200px] px-4 py-4">
                      <Link
                        to={`/incidents/${encodeURIComponent(item.incident_id)}`}
                        className="hover:text-accent"
                      >
                        {item.incident_title}
                      </Link>
                    </td>
                    <td
                      className="px-4 py-4 font-mono text-xs text-text-muted"
                      title={item.id}
                    >
                      {String(item.id).slice(0, 8)}
                    </td>
                    <td className="px-4 py-4 text-xs">{item.status}</td>
                    <td className="whitespace-nowrap px-4 py-4 text-xs text-text-secondary">
                      {formatDate(item.recorded_at)}
                    </td>
                    <td className="px-4 py-4">
                      <button
                        type="button"
                        onClick={() => setParams({ id: item.id })}
                        className="text-xs text-accent hover:underline"
                      >
                        View result
                      </button>
                    </td>
                  </tr>
                ))}
                {!array(data.items).length && (
                  <tr>
                    <td colSpan={5} className="px-5 py-8 text-sm leading-6 text-text-secondary">
                      No matching saved runs. Older results created before
                      history was installed remain on their incident pages.
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>

          <div className="mt-4 flex items-center justify-between text-xs text-text-muted">
            <span>{data.total} saved runs</span>
            <div className="flex items-center gap-4">
              <button
                type="button"
                disabled={page === 0}
                onClick={() => setPage((value) => value - 1)}
                className="disabled:opacity-40"
              >
                Previous
              </button>
              <span>Page {page + 1}</span>
              <button
                type="button"
                disabled={(page + 1) * 10 >= data.total}
                onClick={() => setPage((value) => value + 1)}
                className="disabled:opacity-40"
              >
                Next
              </button>
            </div>
          </div>
        </>
      )}

      {selectedId && (
        <>
          <button
            type="button"
            onClick={() => setParams({})}
            className="mt-7 text-sm text-accent hover:underline"
          >
            Close saved result
          </button>
          <SavedResult key={selectedId} id={selectedId} />
        </>
      )}
    </div>
  );
}